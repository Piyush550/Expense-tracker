-- Expense tracker schema. Money is always integer paise (₹1 = 100) in BIGINT columns.
-- Never edit a migration once it has been deployed: add a new numbered file instead.

-- People. A row with auth_uid = NULL is someone who was added (by email, or imported from
-- the old app) but has not signed in yet. Signing in with a verified matching email claims it.
CREATE TABLE users (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  auth_uid    text UNIQUE,
  email       text CHECK (email IS NULL OR email = lower(email)),
  name        text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 40),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_key ON users (email) WHERE email IS NOT NULL;

-- A space is where expenses live. "recurring" spaces (flat groceries) are settled month by
-- month; "one_time" spaces (a trip) are settled once over everything.
CREATE TABLE spaces (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name            text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
  kind            text NOT NULL DEFAULT 'recurring' CHECK (kind IN ('recurring', 'one_time')),
  simplify_debts  boolean NOT NULL DEFAULT true,
  created_by      uuid NOT NULL REFERENCES users(id),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

-- left_at is set instead of deleting, so past expenses keep pointing at a known member.
CREATE TABLE space_members (
  space_id   uuid NOT NULL REFERENCES spaces(id) ON DELETE CASCADE,
  user_id    uuid NOT NULL REFERENCES users(id),
  role       text NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'member')),
  joined_at  timestamptz NOT NULL DEFAULT now(),
  left_at    timestamptz,
  PRIMARY KEY (space_id, user_id)
);
CREATE INDEX space_members_user_idx ON space_members (user_id) WHERE left_at IS NULL;

-- Groups are reusable lists of people ("Boys Flat": Ishan, Piyush) that work across every
-- space: pick one to add its people to a space or to an expense in one click. Visible to
-- the person who made it and to everyone in it; only the maker can change it.
CREATE TABLE groups (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name        text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
  created_by  uuid NOT NULL REFERENCES users(id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX groups_created_by_idx ON groups (created_by);

CREATE TABLE group_members (
  group_id  uuid NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
  user_id   uuid NOT NULL REFERENCES users(id),
  PRIMARY KEY (group_id, user_id)
);
CREATE INDEX group_members_user_idx ON group_members (user_id);

-- id is generated by the client so a retried POST cannot create the expense twice.
CREATE TABLE expenses (
  id            uuid PRIMARY KEY,
  space_id      uuid NOT NULL REFERENCES spaces(id) ON DELETE CASCADE,
  description   text NOT NULL CHECK (char_length(description) BETWEEN 1 AND 100),
  amount_paise  bigint NOT NULL CHECK (amount_paise > 0 AND amount_paise <= 10000000000),
  payer_id      uuid NOT NULL REFERENCES users(id),
  split_type    text NOT NULL CHECK (split_type IN ('equal', 'exact', 'percent', 'shares')),
  spent_on      date NOT NULL,
  remarks       text NOT NULL DEFAULT '' CHECK (char_length(remarks) <= 500),
  version       integer NOT NULL DEFAULT 1,
  created_by    uuid NOT NULL REFERENCES users(id),
  updated_by    uuid NOT NULL REFERENCES users(id),
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  deleted_at    timestamptz,
  deleted_by    uuid REFERENCES users(id)
);
CREATE INDEX expenses_space_spent_idx ON expenses (space_id, spent_on DESC, created_at DESC) WHERE deleted_at IS NULL;

-- Each participant's computed share, fixed when the expense is saved, so balances are a SUM.
-- split_value keeps what was typed: paise for 'exact', basis points (100% = 10000) for
-- 'percent', units for 'shares', NULL for 'equal'.
CREATE TABLE expense_shares (
  expense_id   uuid NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
  user_id      uuid NOT NULL REFERENCES users(id),
  share_paise  bigint NOT NULL CHECK (share_paise >= 0),
  split_value  bigint CHECK (split_value IS NULL OR split_value >= 0),
  PRIMARY KEY (expense_id, user_id)
);
CREATE INDEX expense_shares_user_idx ON expense_shares (user_id);

-- Money that actually moved between two members. `period` is the month (its first day)
-- the payment settles, which can differ from paid_on: September's dues paid on 2 October.
CREATE TABLE settlements (
  id            uuid PRIMARY KEY,
  space_id      uuid NOT NULL REFERENCES spaces(id) ON DELETE CASCADE,
  from_user_id  uuid NOT NULL REFERENCES users(id),
  to_user_id    uuid NOT NULL REFERENCES users(id),
  amount_paise  bigint NOT NULL CHECK (amount_paise > 0 AND amount_paise <= 10000000000),
  paid_on       date NOT NULL,
  period        date NOT NULL CHECK (extract(day FROM period) = 1),
  note          text NOT NULL DEFAULT '' CHECK (char_length(note) <= 200),
  created_by    uuid NOT NULL REFERENCES users(id),
  created_at    timestamptz NOT NULL DEFAULT now(),
  deleted_at    timestamptz,
  deleted_by    uuid REFERENCES users(id),
  CHECK (from_user_id <> to_user_id)
);
CREATE INDEX settlements_space_period_idx ON settlements (space_id, period DESC) WHERE deleted_at IS NULL;
